	if KG_cs ~= '开' then
		gg.toast('传送功能初始化失败❌请重启游戏与辅助')
		return false
	end
	
	local tmp0 = gg.getValues(dthx)
	for i = 1, #rycs_id do -- i为当前地图索引，cms为目标地图索引、草！！之前这里用错了一直出问题
		if tmp0[1].value == rycs_id[i][2] then
			if i == csm then
				gg.toast('你已在【' .. rycs_id[i][3] .. '】,无需传送')
				return false
			elseif i == 36 then
				gg.toast('请完成献祭，然后前往下个地图')
				if csm == 1 then csm = 40 end
				rycs_idx = rycs_id[csm][2]
				rycs_yd = true
				A_bfy()
			elseif i == 37 or i == 38 or i == 39 then
				if csm == 1 then csm = 40 end
				rycs_idx = rycs_id[csm][2]
				rycs_yd = true
			else
				rycs_idx = rycs_id[csm][2]
				rycs_yd = false
			end
		end
	end
	
	local tmp = {}
	local tmp1 = {}
	for i = 1, 24 do
		tmp[i] = 0
		tmp[i] = string.byte(rycs_id[csm][1], i, i)
		if tmp[i] == nil then tmp[i] = 0 end
		tmp1[i] = {}
		tmp1[i].address = yjhx + i - 1
		tmp1[i].flags = gg.TYPE_BYTE
		tmp1[i].value = tmp[i]
		gg.setValues(tmp1)
	end
	return true
end

function A_rycs_2() -- 任意传送，传送，判定地图并等待
	if rycs_yd == true then
		gg.toast(
			'已设置好传送，请打开设置，手动回遇境，即可到达目的地')
		repeat
			gg.sleep(1000)
			local tmp0 = gg.getValues(dthx)
			if gg.isVisible(true) then
				gg.setVisible(false)
				gg.alert(
					'已设置好传送，请打开设置，手动回遇境，即可到达目的地')
			end
		until tmp0[1].value == rycs_idx
	else
		A_xggy(0);
		A_jiasu(15);
		gg.sleep(400);
		A_xggy(Num_xggy);
		A_jiasu(6)
		
		local tmp = 0
		gg.toast('正在进入地图，请稍后')
		repeat
			gg.sleep(800)
			local tmp0 = gg.getValues(dthx)
			tmp = tmp + 1
			if tmp == 15 then
				gg.toast('长时间未进入地图，请重启辅助')
				break
			end
		until tmp0[1].value == rycs_idx
		A_jiasu(1)
	end
end

