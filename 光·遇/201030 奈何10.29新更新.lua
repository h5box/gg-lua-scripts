function A_PTJG() -- 跑图间隔
	local tmp = gg.prompt({
			'瞬移间隔（默认300毫秒）[50,∞]',
			'过图间隔（默认3000毫秒）[500,∞]'
			}, {[1] = sleep_time, [2] = trans_time}, {[1] = 'number', [2] = 'number'})
	
	if tmp[1] == '' or tmp[2] == '' then
		gg.toast('不要留空空，你让我怎么办o(￣ヘ￣o＃)')
		return 0
	end
	
	tmp[1] = tonumber(tmp[1])
	tmp[2] = tonumber(tmp[2])
	if tmp[1] < 50 or tmp[2] < 500 then
		gg.toast('不要逗我啦，这么小的间隔时间，\n我才反应不过来呢，哼╭(╯^╰)╮')
	elseif tmp[1] >= 50 and tmp[2] >= 500 then
		sleep_time = tmp[1]
		trans_time = tmp[2]
		gg.toast('✔设置成功ヾﾉ≧∀≦)o\n\n瞬移间隔：'..sleep_time..'毫秒\n过图间隔：'..trans_time..'毫秒')
		SaveSchedule(-1)
	end
end

