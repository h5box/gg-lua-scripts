function M_jjxz() -- 季节先祖，源码【东街猫儿】
	FX = 'M_jjxz'
	local choiceData = {}
	local k = 1
	local kMap = {}
	for i = 1, #TravelSpirit do
		if i == 1 then
			choiceData[k] =
			'---↓感恩节先祖(请选择下方先祖，不要选择此标题)---'
		elseif i == 2 then
			choiceData[k] =
			'---↓追光季先祖(请选择下方先祖，不要选择此标题)---'
		elseif i == 3 then
			choiceData[k] =
			'---↓归属季先祖(请选择下方先祖，不要选择此标题)---'
		elseif i == 4 then
			choiceData[k] =
			'---↓凛冬季先祖(请选择下方先祖，不要选择此标题)---'
		elseif i == 5 then
			choiceData[k] =
			'---↓魔法季先祖(请选择下方先祖，不要选择此标题)---'
		end
		k = k + 1
		
		for ii = 1, #TravelSpirit[i] do
			local strK = tostring(k)
			choiceData[k] = '  ' .. tostring(ii) .. '. ' ..
			TravelSpirit[i][ii][2]
			local key = 'P' .. strK
			kMap[key] = {TravelSpirit[i][ii][1], TravelSpirit[i][ii][2]}
			k = k + 1
		end
	end
	local backIdx = k + 1
	local MainIdx = backIdx + 1
	choiceData[backIdx] = '🔙返回上一页'
	choiceData[MainIdx] = '💫返回主页'
	
	local spirit_menu = gg.multiChoice(choiceData, nil,
		'请选择需要重新体验的旅行先祖')
	
	if spirit_menu == nil then
		gg.toast('操作已取消！')
	elseif (spirit_menu[backIdx]) then
		M_GN()
	elseif (spirit_menu[MainIdx]) then
		Main()
	else
		local switchedSpirit = {}
		for i, v in pairs(spirit_menu) do
			if (v) then
				local key = 'P' .. i
				if kMap[key] ~= nil then
					local sp = kMap[key]
					sp.k = i
					table.insert(switchedSpirit, sp)
				end
			end
		end
		
		if #switchedSpirit <= 0 then
			gg.toast('请选择先祖，不要选择标题！')
			return
		end
		
		local notFoundSpirit = ''
		local selectedSpirit = {}
		
		gg.setRanges(gg.REGION_C_ALLOC)
		for q, val in pairs(switchedSpirit) do
			repeat
				gg.clearResults()
				Chen_searchNumber(tostring(val[1]), gg.TYPE_QWORD)
				local resCount = gg.getResultCount()
				if resCount > 0 then
					local res = gg.getResults(resCount)
					res[3].value = 0
					res[3].freeze = true
					local result = {[1] = res[3]}
					gg.addListItems(result)
					
					selectedSpirit[val.k] = true
				else
					-- 未找到数据
					notFoundSpirit = notFoundSpirit .. '编号：' ..
					tostring(val[1]) .. '，' .. val[2] ..
					'\n'
				end
			until (selectedSpirit[val.k])
		end
		
		if #notFoundSpirit > 0 then
			gg.alert('❌以下先祖未操作成功：\n' .. notFoundSpirit)
		else
			gg.toast('操作完成✔去寻找先祖吧')
		end
	end
end

