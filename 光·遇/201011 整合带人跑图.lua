-- 任意门菜单
function DoorMenu()
    local menuList = {}
    for i = 1, 40 do menuList[i] = '『' .. door[i][3] .. '』' end

    menuList[41] = '『返回上页(主菜单)』'

    local menu = gg.choice(menuList, nil, '选择要传送的地点')

    local currentLocation = getLocation()

    if menu == nil then
        gg.isVisible(false)
    elseif menu == currentLocation then
        gg.toast("你已经在 『" .. door[menu][3] .. "』")
    elseif menu == 36 then
        gg.toast('『伊甸』 不支持任意门')
    elseif menu == 41 then
        TempMenu = "HomeMenu"
        HomeMenu()
    else
        local gradeList = gg.getValues(data[3])
        local tempGrade = gradeList[1].value
        backCandleSpace(menu)
        data[3][1].value = 0
        gg.setValues(data[3])
        speedUp(5)
        gg.sleep(1000)
        data[3][1].value = tempGrade
        gg.setValues(data[3])
        currentLocation = getLocation()
        while (menu ~= currentLocation) do
            currentLocation = getLocation()
            gg.sleep(1000)
        end
        backCandleSpace(1)
        resetSpeed()
    end

    Menu = nil
end

