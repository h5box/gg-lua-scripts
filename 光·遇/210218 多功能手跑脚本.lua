      local tmp = {}
      for i, v in ipairs(zb) do
        tmp[#tmp + 1] = {}
        tmp[#tmp].address = v.address - 196
        tmp[#tmp].flags = 4
      end
      tmp = gg.getValues(tmp)
      for i, v in ipairs(tmp) do
        if v.value == 1 then
          Address_clos = tmp[i].address
          break
        end
